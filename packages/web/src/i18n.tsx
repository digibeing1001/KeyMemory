const dictionaries: Record<Language, Record<string, string>> = { zh, en };

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  layerLabel: (layer: Layer) => string;
  layerHelp: (layer: Layer) => string;
  memoryKindLabel: (kind?: MemoryKind | string | null) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === 'en' ? 'en' : 'zh';
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: string, vars?: Record<string, string | number>) => {
      const template = dictionaries[language][key] ?? dictionaries.zh[key] ?? key;
      return interpolate(template, vars);
    };

    return {
      language,
      setLanguage: setLanguageState,
      t,
      layerLabel: (layer) => t(`layer.${layer}`),
      layerHelp: (layer) => t(`layer.${layer}.help`),
      memoryKindLabel: (kind) => (kind ? t(`kind.${kind}`) : t('kind.raw_note')),
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
